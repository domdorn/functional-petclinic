package com.dominikdorn.zazr.wither;

import java.io.IOException;
import java.io.Writer;
import java.util.List;
import java.util.Set;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;

/**
 * Generates a {@code <Record>With} interface of fluent copy methods for every
 * {@code record} annotated with {@link GenerateWithers}. Each record component {@code c}
 * of type {@code T} yields:
 *
 * <pre>{@code
 * default <Record> withC(T c) { return new <Record>(..., c, ...); }
 * }</pre>
 *
 * where every other component is copied via its accessor. The record implements the
 * generated interface, whose abstract accessor declarations are satisfied by the record's
 * own component accessors.
 */
@SupportedAnnotationTypes("com.dominikdorn.zazr.wither.GenerateWithers")
public class WithersProcessor extends AbstractProcessor {

	@Override
	public SourceVersion getSupportedSourceVersion() {
		// Support whatever the running JDK supports (RELEASE_28 includes value records).
		return SourceVersion.latestSupported();
	}

	@Override
	public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
		for (Element element : roundEnv.getElementsAnnotatedWith(GenerateWithers.class)) {
			if (element.getKind() != ElementKind.RECORD) {
				error(element, "@GenerateWithers may only be placed on a record");
				continue;
			}
			generate((TypeElement) element);
		}
		return true;
	}

	private void generate(TypeElement record) {
		String pkg = this.processingEnv.getElementUtils().getPackageOf(record).getQualifiedName().toString();
		String recordName = record.getSimpleName().toString();
		String interfaceName = recordName + "With";
		String interfaceFqn = pkg.isEmpty() ? interfaceName : pkg + "." + interfaceName;
		List<? extends RecordComponentElement> components = record.getRecordComponents();
		boolean isPublic = record.getModifiers().contains(Modifier.PUBLIC);

		StringBuilder out = new StringBuilder();
		if (!pkg.isEmpty()) {
			out.append("package ").append(pkg).append(";\n\n");
		}
		out.append("// Generated by value-records-wither. Do not edit.\n");
		out.append(isPublic ? "public " : "").append("interface ").append(interfaceName).append(" {\n\n");

		// Abstract accessors — satisfied by the record's own component accessors.
		for (RecordComponentElement component : components) {
			out.append("\t").append(component.asType()).append(" ").append(component.getSimpleName()).append("();\n");
		}
		out.append("\n");

		// One fluent copy method per component.
		for (RecordComponentElement target : components) {
			String name = target.getSimpleName().toString();
			String method = "with" + Character.toUpperCase(name.charAt(0)) + name.substring(1);
			out.append("\tdefault ").append(recordName).append(" ").append(method);
			out.append("(").append(target.asType()).append(" ").append(name).append(") {\n");
			out.append("\t\treturn new ").append(recordName).append("(");
			for (int i = 0; i < components.size(); i++) {
				if (i > 0) {
					out.append(", ");
				}
				RecordComponentElement component = components.get(i);
				boolean isTarget = component.getSimpleName().contentEquals(name);
				out.append(isTarget ? name : component.getSimpleName() + "()");
			}
			out.append(");\n\t}\n\n");
		}
		out.append("}\n");

		try {
			JavaFileObject file = this.processingEnv.getFiler().createSourceFile(interfaceFqn, record);
			try (Writer writer = file.openWriter()) {
				writer.write(out.toString());
			}
		}
		catch (IOException ex) {
			error(record, "Failed to write " + interfaceFqn + ": " + ex.getMessage());
		}
	}

	private void error(Element element, String message) {
		this.processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element);
	}

}
